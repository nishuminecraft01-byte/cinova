// Search helper that matches query or searches online
export async function searchMoviesOnline(query: string): Promise<Movie[]> {
  const q = query.toLowerCase().trim();
  const matched = POPULAR_TMDB_CATALOG.filter((item) => {
    return (
      item.title.toLowerCase().includes(q) ||
      (item.originalTitle && item.originalTitle.toLowerCase().includes(q)) ||
      (item.genre && item.genre.some((g) => g.toLowerCase().includes(q))) ||
      (item.industry && item.industry.toLowerCase().includes(q)) ||
      (item.franchiseName && item.franchiseName.toLowerCase().includes(q))
    );
  });

  return matched.map((item) => convertCatalogItemToMovie(item));
}

export function convertCatalogItemToMovie(item: Partial<Movie> & { tmdbId: string; title: string }): Movie {
  const id = item.id || `tmdb-${item.tmdbId}`;
  
  // Auto detect industry if not explicitly defined
  const detectedIndustry =
    item.industry ||
    (item.language === "Hindi" || item.language === "Telugu" || item.language === "Tamil" || item.language === "Kannada"
      ? "bollywood"
      : item.language === "Japanese" && (item.genre?.includes("Animation") || item.type === "series")
      ? "anime"
      : item.language === "Korean"
      ? "k-drama"
      : "hollywood");

  return {
    id,
    tmdbId: item.tmdbId,
    title: item.title,
    originalTitle: item.originalTitle || item.title,
    tagline: item.tagline || "Streaming on CINOVA",
    description: item.description || "Exciting cinematic experience available across all CINOVA streaming servers.",
    posterUrl: item.posterUrl || "",
    backdropUrl: item.backdropUrl || item.posterUrl || "",
    videoUrl: item.videoUrl || "",
    trailerUrl: item.trailerUrl || "",
    duration: item.duration || 120,
    releaseYear: item.releaseYear || 2024,
    rating: item.rating || "PG-13",
    imdbScore: item.imdbScore || 8.7,
    matchPercentage: item.matchPercentage || 96,
    genre: item.genre || ["Action", "Sci-Fi"],
    type: item.type || "movie",
    industry: detectedIndustry,
    language: item.language || "English",
    availableLanguages: item.availableLanguages || ["English"],
    subtitles: item.subtitles || ["English [CC]"],
    quality: item.quality || "4K UHD",
    audioSpecs: item.audioSpecs || "Dolby Atmos 5.1",
    directors: item.directors || ["CINOVA Studios"],
    cast: item.cast || [{ name: "Lead Star", character: "Hero" }],
    isTrending: item.isTrending ?? true,
    isFeatured: item.isFeatured ?? false,
    isPopular: item.isPopular ?? true,
    isRecentlyAdded: item.isRecentlyAdded ?? true,
    views: item.views || 100000,
    seasons: item.seasons,
    franchiseId: item.franchiseId,
    franchiseName: item.franchiseName,
  };
}
