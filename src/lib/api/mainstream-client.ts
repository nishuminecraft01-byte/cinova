/**
 * Returns mainstream tracks filtered by category.
 */
export function getMainstreamTracksByCategory(categorySlug: string, limit: number = 24): Song[] {
  const slug = categorySlug.toLowerCase().trim();

  // 1. Dedicated Marathi Categories Handling
  if (slug === "marathi" || slug.startsWith("marathi-")) {
    const marathiTracks = getMarathiTracksByCategory(slug, limit);
    if (marathiTracks.length > 0) return marathiTracks;
  }

  // Match by category field or genre mapping
  const matched = MAINSTREAM_TRACKS.filter((t) => {
    const g = (t.genre || "").toLowerCase();
    const c = (t.category || "").toLowerCase();

    if (c === slug) return true;
    if (slug === "trending" && t.trending) return true;
    if (slug === "latest-releases" && (t.year === 2024 || t.trending)) return true;
    if (slug === "hindi" && (c === "hindi" || c === "bollywood" || c === "romantic" || g.includes("hindi") || g.includes("bollywood"))) return true;
    if (slug === "punjabi" && (c === "punjabi" || g.includes("punjabi"))) return true;
    if (slug === "marathi" && (c === "marathi" || g.includes("marathi") || g.includes("lavani"))) return true;
    if ((slug === "english" || slug === "international") && (c === "english" || c === "international")) return true;
    if (slug === "devotional" && (c === "devotional" || g.includes("devotional") || g.includes("sufi"))) return true;
    if (slug === "romantic" && (c === "romantic" || g.includes("romantic") || g.includes("soul") || g.includes("melody"))) return true;
    if (slug === "party" && (c === "party" || g.includes("party") || g.includes("dance") || g.includes("club") || g.includes("banger"))) return true;
    if ((slug === "sad-songs" || slug === "sad") && (c === "sad-songs" || g.includes("sad") || g.includes("ballad") || g.includes("heartbreak"))) return true;
    if ((slug === "old-classics" || slug === "retro") && (c === "old-classics" || g.includes("retro") || (t.year && t.year < 2000))) return true;
    return false;
  });

  if (matched.length > 0) {
    return matched.slice(0, limit);
  }

  // Fallback to general tracks if exact category has fewer items
  return MAINSTREAM_TRACKS.slice(0, limit);
}

