/**
 * Searches mainstream tracks by keyword.
 */
export function searchMainstreamTracks(query: string, limit: number = 12): Song[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];

  return MAINSTREAM_TRACKS.filter(
    (t) =>
      t.title.toLowerCase().includes(q) ||
      t.artist.toLowerCase().includes(q) ||
      (t.album && t.album.toLowerCase().includes(q)) ||
      t.genre.toLowerCase().includes(q)
  ).slice(0, limit);
}

/**
 * Returns mainstream artist by ID with their songs.
 */
export function getMainstreamArtistById(id: string): { artist: Artist; tracks: Song[] } | null {
  const artist = MAINSTREAM_ARTISTS.find((a) => a.id === id);
  if (!artist) return null;
  const tracks = MAINSTREAM_TRACKS.filter(
    (t) => t.artistId === id || t.artist.toLowerCase().includes(artist.name.toLowerCase())
  );
  return { artist, tracks };
}

/**
 * Returns mainstream album by ID with its songs.
 */
export function getMainstreamAlbumById(id: string): { album: Album; tracks: Song[] } | null {
  const album = MAINSTREAM_ALBUMS.find((a) => a.id === id);
  if (!album) return null;
  const tracks = MAINSTREAM_TRACKS.filter(
    (t) => t.albumId === id || (t.album && t.album.toLowerCase() === album.title.toLowerCase())
  );
  return { album: { ...album, songs: tracks }, tracks };
}
